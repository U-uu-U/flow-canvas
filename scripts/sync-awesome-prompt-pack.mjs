import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const upstreamRoot = resolve(process.argv[2] || join(root, '..', 'awesome-gpt-image-2'));
const sourceFile = join(upstreamRoot, 'data', 'style-library.json');
const licenseFile = join(upstreamRoot, 'LICENSE');
const outputFile = join(root, 'src', 'prompt-packs', 'awesome-gpt-image-2.js');
const source = JSON.parse(readFileSync(sourceFile, 'utf8'));
const licenseNotice = readFileSync(licenseFile, 'utf8').trim();
const categoryLabels = new Map(source.categories.map(category => [category.value, category.title.zh]));

const pack = {
    id: 'awesome-gpt-image-2',
    name: 'Awesome GPT Image 2',
    version: source.version,
    description: '面向图片生成的轻量模板库',
    source: source.repository,
    license: 'MIT',
    licenseNotice,
    attribution: 'Prompt library derived from freestylefly/awesome-gpt-image-2',
    models: ['gpt-image-2'],
    categories: source.categories.map(category => ({
        id: category.value,
        name: category.title.zh
    })),
    templates: source.templates.map(template => ({
        id: template.id,
        name: template.title.zh,
        category: template.category,
        categoryName: categoryLabels.get(template.category) || template.category,
        summary: template.description.zh,
        styles: template.styles,
        scenes: template.scenes,
        tags: template.tags,
        guidance: template.guidance.zh,
        pitfalls: template.pitfalls.zh
    }))
};

const output = `// Generated by scripts/sync-awesome-prompt-pack.mjs.\n`
    + `// Source: ${source.repository}\n`
    + `export default ${JSON.stringify(pack, null, 2)};\n`;

mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(outputFile, output);
console.log(`Wrote ${pack.templates.length} templates to ${outputFile}`);
